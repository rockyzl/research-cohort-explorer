"""Query service shared by the API, the cohort builder, and the evaluation harness.

Every SQL string, whether typed by a user, generated by the LLM, or built by the cohort builder,
goes through the same path: validate (layer 1) -> output-policy rewrite -> validate the rewrite ->
execute on the read-only, authorizer-guarded connection (layer 2) -> apply suppression.
"""
from __future__ import annotations

import sqlite3
from functools import lru_cache

from cohort import privacy
from cohort.catalog import load_catalog
from cohort.sqlguard import GuardError, MAX_ROWS, connect_readonly, execute, validate


@lru_cache(maxsize=4)
def _con(role: str) -> sqlite3.Connection:
    return connect_readonly(role)


def run_sql(sql: str, role: str = "researcher") -> dict:
    """Validate + execute + apply the output policy. Never raises for user-caused errors."""
    out = {"sql": sql, "role": role, "ok": False}
    try:
        v = validate(sql, role)
        out["checks"] = list(v.checks)
        pol = privacy.plan(v.tree)
        exec_sql = pol.rewritten_sql
        validate(exec_sql, role)  # the policy rewrite gets no special trust
        res = execute(_con(role), exec_sql)
        cols, rows, n_sup = privacy.apply(res.columns, res.rows, pol)
        ok_export, why = privacy.exportable(v.columns, pol)
        out.update(ok=True, executed_sql=exec_sql, columns=cols, rows=rows, row_count=len(rows),
                   truncated=res.truncated, max_rows=MAX_ROWS, suppressed_cells=n_sup,
                   aggregate=pol.aggregate, policy_notes=pol.notes, exportable=ok_export,
                   export_note=why, elapsed_ms=res.elapsed_ms,
                   columns_read=sorted(f"{t}.{c}" for t, c in v.columns))
        out["checks"].append(f"executed on read-only connection with engine authorizer (role '{role}')")
        if n_sup:
            out["checks"].append(f"small-cell suppression blanked {n_sup} cell(s) (n<{privacy.THRESHOLD})")
    except GuardError as e:
        out.update(error=e.message, error_stage=e.stage)
    return out


def run_sql_raw(sql: str, role: str = "researcher"):
    """Validated execution WITHOUT the output policy. Evaluation harness only (scores raw answers)."""
    v = validate(sql, role)
    return execute(_con(role), v.sql)


# ------------------------------------------------------------------------------------------------
# Structured cohort builder: filters -> deterministic SQL (no LLM)
# ------------------------------------------------------------------------------------------------
FILTER_FIELDS = {
    "stage_group": ("clinical", "stage_group"),
    "er_status": ("clinical", "er_status"),
    "pr_status": ("clinical", "pr_status"),
    "her2_status": ("clinical", "her2_status"),
    "pam50_subtype": ("clinical", "pam50_subtype"),
    "histological_type": ("clinical", "histological_type"),
    "gender": ("patients", "gender"),
    "menopause_status": ("patients", "menopause_status"),
}
REQUIRE_FLAGS = ["has_survival", "has_receptor_status", "has_rna_tumor", "has_rna_normal",
                 "has_pathology_report", "has_diagnostic_slide"]
ALIAS = {"patients": "p", "clinical": "c", "data_availability": "a"}


def _q(v: str) -> str:
    return "'" + v.replace("'", "''") + "'"


def cohort_sql(filters: dict) -> str:
    cat = load_catalog()
    where = []
    for key, (table, col) in FILTER_FIELDS.items():
        vals = filters.get(key) or []
        if isinstance(vals, str):
            vals = [vals]
        if not vals:
            continue
        allowed = set(cat.columns[table][col].allowed_values)
        bad = [x for x in vals if x not in allowed]
        if bad:
            raise GuardError("cohort_filter", f"{key}: {bad} not in catalog allowed values")
        where.append(f"{ALIAS[table]}.{col} IN ({', '.join(_q(x) for x in vals)})")
    if filters.get("triple_negative") is not None:
        where.append(f"c.triple_negative = {int(bool(filters['triple_negative']))}")
    if filters.get("age_min") is not None:
        where.append(f"p.age_at_diagnosis >= {int(filters['age_min'])}")
    if filters.get("age_max") is not None:
        where.append(f"p.age_at_diagnosis <= {int(filters['age_max'])}")
    for flag in filters.get("require") or []:
        if flag not in REQUIRE_FLAGS:
            raise GuardError("cohort_filter", f"unknown availability flag {flag!r}")
        where.append(f"a.{flag} = 1")
    sql = ("SELECT COUNT(*) AS patients, SUM(a.has_survival) AS with_survival, "
           "SUM(a.has_receptor_status) AS with_receptor_status, SUM(a.has_rna_tumor) AS with_rna_tumor, "
           "SUM(a.has_pathology_report) AS with_pathology_report, "
           "SUM(a.has_diagnostic_slide) AS with_diagnostic_slide, "
           "SUM(a.has_rna_tumor * a.has_pathology_report * a.has_diagnostic_slide) AS with_rna_report_slide "
           "FROM patients p JOIN clinical c ON c.patient_id = p.patient_id "
           "JOIN data_availability a ON a.patient_id = p.patient_id")
    if where:
        sql += " WHERE " + " AND ".join(where)
    return sql


def cohort_breakdown_sql(filters: dict, by: str) -> str:
    if by not in FILTER_FIELDS:
        raise GuardError("cohort_filter", f"cannot break down by {by!r}")
    table, col = FILTER_FIELDS[by]
    base = cohort_sql(filters)
    where = base.split(" WHERE ", 1)[1] if " WHERE " in base else None
    sql = (f"SELECT {ALIAS[table]}.{col} AS {col}, COUNT(*) AS patients "
           "FROM patients p JOIN clinical c ON c.patient_id = p.patient_id "
           "JOIN data_availability a ON a.patient_id = p.patient_id")
    if where:
        sql += " WHERE " + where
    return sql + f" GROUP BY {ALIAS[table]}.{col} ORDER BY patients DESC"


def build_cohort(filters: dict, role: str = "researcher", breakdown: str | None = "stage_group") -> dict:
    try:
        sql = cohort_sql(filters)
        bd_sql = cohort_breakdown_sql(filters, breakdown) if breakdown else None
    except GuardError as e:
        return {"ok": False, "error": e.message, "error_stage": e.stage}
    out = {"ok": True, "filters": filters, "summary": run_sql(sql, role)}
    if bd_sql:
        out["breakdown"] = run_sql(bd_sql, role)
    return out
